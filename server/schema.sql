-- Publication-supplied minimal schema inferred from sync.py's INSERT contract.
-- Run while connected to your own iot_db. This does not create users/databases.
-- Existing tables are preserved; inspect their schema before applying.
CREATE TABLE IF NOT EXISTS public.sensor_data (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,
    temperature DOUBLE PRECISION NOT NULL,
    humidity DOUBLE PRECISION NOT NULL,
    light_lux DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_sensor_device_time
    ON public.sensor_data(device_id, recorded_at);
